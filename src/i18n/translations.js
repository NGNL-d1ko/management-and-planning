export const translate = (language, key, params = {}) => {
  const parts = key.split('.');
  const dictionary = translations[language] || translations.ru;
  const fallbackDictionary = translations.ru;

  const read = (source) => parts.reduce((value, part) => (
    value && Object.prototype.hasOwnProperty.call(value, part) ? value[part] : undefined
  ), source);

  const template = read(dictionary) ?? read(fallbackDictionary) ?? key;

  if (typeof template !== 'string') {
    return template;
  }

  return Object.entries(params).reduce(
    (result, [name, value]) => result.replaceAll(`{{${name}}}`, value ?? ''),
    template,
  );
};
